<section class="editorial">
    <div class="wrap-narrow">
        <p class="editorial-kicker">The argument</p>
        <h2>Translated is not the same as built.</h2>
        <div class="editorial-body" style="margin-top: var(--space-6);">
            <p class="dropcap">
                For thirty years, the way Indian households have managed daily life is by retrofitting tools
                someone else built somewhere else. Calendars made in California. To-do lists made in Toronto.
                Productivity apps designed around the rhythms of a Tuesday morning in Munich. We've adapted.
                Indians always adapt. We are the most Excel-fluent civilization on Earth, and we will make
                anything work.
            </p>
            <p>
                But adapting isn't the same as belonging. A Western productivity tool is a glove built for a
                different hand. You can wear it. It mostly fits. But it pinches at the joint where your
                thumb actually moves &mdash; the joint where the maid's salary lives next to the property tax,
                where the festival prep cycle overlaps with the mediclaim renewal, where Hinglish meets the
                LPG receipt, where one person tracks fifty things across nine languages because that is
                <em>what an Indian household is.</em>
            </p>
        </div>

        <blockquote class="pull-quote">
            We don't have a productivity problem.
            We have an <em>imported productivity</em> problem.
            <span class="pull-quote-cite">&mdash; the case for Pratyek, in one sentence.</span>
        </blockquote>

        <div class="editorial-body">
            <p>
                When a global product comes to India, the playbook is familiar: add a rupee symbol, support
                Hindi in the keyboard, run a Diwali campaign, hire an Indian face for the hero shot.
                Call it <em>localization</em>. It isn't. It's costume. The product underneath is still the same
                product, still solving the same problem the same way it does in San Francisco.
            </p>
            <p>
                Costume doesn't fit a country whose middle class invented WhatsApp groups for everything,
                whose grandmothers send voice notes in three languages in one sentence, whose family CFOs
                track milkmen and EMI dates and Ayurvedic refills and Adani and Bajaj Allianz and BMC and
                BBMP all in one head, all the time.
            </p>
            <p>
                India deserves products that are <strong>not Indianized but Indian.</strong> Built here.
                For us. From the first commit.
            </p>
        </div>
    </div>
</section>

